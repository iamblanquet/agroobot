create table if not exists public.predio (id bigint generated by default as identity primary key, nombre text not null, superficie_legal_ha numeric(12,2) not null default 0, superficie_util_ha numeric(12,2) not null default 0, regimen text, poligono_geojson text);
create table if not exists public.obra (id bigint generated by default as identity primary key, nombre text not null, proyecto_id bigint not null references public.proyecto(id) on delete cascade, fase_actual text, estado text not null default 'operacion', tg_thread_id text);
create table if not exists public.obra_predio (obra_id bigint not null references public.obra(id) on delete cascade, predio_id bigint not null references public.predio(id) on delete cascade, primary key (obra_id, predio_id));
create table if not exists public.reporte (id bigint generated by default as identity primary key, client_uuid text not null unique, proyecto_id bigint references public.proyecto(id) on delete set null, hito_id bigint references public.hito(id) on delete set null, tarea_id bigint references public.tarea(id) on delete set null, obra_id bigint references public.obra(id) on delete set null, recibido_en timestamptz default now(), fecha_operativa date not null, hora_offline text, creado_offline timestamptz, autor_nombre text not null, texto_original text, nota text, estado text not null default 'confirmado', es_sin_actividad boolean not null default false, motivo_sin_actividad text);
create table if not exists public.reporte_linea (id bigint generated by default as identity primary key, reporte_id bigint not null references public.reporte(id) on delete cascade, predio_id bigint references public.predio(id) on delete set null, actividad_id text, cantidad numeric(12,2) not null default 0, unidad text not null default 'ha', cantidad_ha numeric(12,2) not null default 0, fuente text not null default 'campo');
create table if not exists public.reporte_cuadrilla (id bigint generated by default as identity primary key, reporte_id bigint not null references public.reporte(id) on delete cascade, rol_id text not null, headcount integer not null default 0);
create table if not exists public.entidad (id bigint generated by default as identity primary key, nombre text not null unique, tipo text default 'empresa', contacto text, activo boolean not null default true);
create table if not exists public.maquina (id bigint generated by default as identity primary key, codigo text not null unique, nombre text not null default '', tipo text not null default 'tractor', modelo text not null, propietaria_id bigint references public.entidad(id) on delete set null, operadora_id bigint references public.entidad(id) on delete set null, umbral_servicio_hrs numeric(12,2) not null default 300, horometro_actual numeric(12,2) not null default 0, ultimo_servicio_hr numeric(12,2) not null default 0, alerta_mantenimiento boolean not null default false);
create table if not exists public.lectura_maquina (id bigint generated by default as identity primary key, reporte_id bigint not null references public.reporte(id) on delete cascade, maquina_id bigint not null references public.maquina(id) on delete cascade, horometro_inicio numeric(12,2) not null, horometro_fin numeric(12,2) not null, horas_trabajadas numeric(12,2) not null default 0, litros_diesel numeric(12,2) not null default 0);
create table if not exists public.incidencia (id bigint generated by default as identity primary key, folio text not null unique, tipo text not null, obra_id bigint not null references public.obra(id) on delete cascade, estado text not null default 'abierta', abierta_en timestamptz default now(), cerrada_en timestamptz, causa_raiz text);
create table if not exists public.material (id bigint generated by default as identity primary key, obra_id bigint not null references public.obra(id) on delete cascade, nombre text not null, requerido numeric(12,2) not null default 0, en_sitio numeric(12,2) not null default 0, pedido numeric(12,2) not null default 0, unidad text not null default 'pza', eta date);
create table if not exists public.medicion (id bigint generated by default as identity primary key, proyecto_id bigint not null references public.proyecto(id) on delete cascade, hectareas numeric(12,2) not null default 0, fecha date not null, fuente text not null default 'dron', archivo_ruta text);
create table if not exists public.reporte_foto (id bigint generated by default as identity primary key, reporte_id bigint not null references public.reporte(id) on delete cascade, archivo_ruta text not null, url text not null, descripcion text, creado_en timestamptz default now());
create table if not exists public.activo_fijo (id bigint generated by default as identity primary key, codigo text not null unique, nombre text not null, tipo text not null, ubicacion text not null, predio_id bigint references public.predio(id) on delete set null, obra_id bigint references public.obra(id) on delete set null, ultima_lectura_fecha date, estado_operativo text not null default 'operativo');
create table if not exists public.lectura_activo_fijo (id bigint generated by default as identity primary key, activo_fijo_id bigint not null references public.activo_fijo(id) on delete cascade, fecha date not null, reporte_id bigint references public.reporte(id) on delete set null, inspeccionado_por text not null, observaciones text, estado_operativo text not null default 'operativo', creado_en timestamptz default now());


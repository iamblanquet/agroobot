create extension if not exists pgcrypto;

create table if not exists public.usuario (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  nombre text not null default '',
  rol text not null default 'campo',
  pin text unique,
  activo boolean not null default true,
  tg_user_id text,
  tg_chat_id text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.proyecto (
  id bigint generated by default as identity primary key,
  nombre text not null,
  tipo text,
  ciclo text,
  fecha_inicio date,
  fecha_fin date,
  superficie_meta_ha numeric(12,2) not null default 0,
  gerente_id bigint references public.usuario(id) on delete set null,
  estado text not null default 'activo',
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.hito (
  id bigint generated by default as identity primary key,
  proyecto_id bigint not null references public.proyecto(id) on delete cascade,
  nombre text not null,
  descripcion text,
  orden integer not null default 1,
  fecha_meta date,
  superficie_meta_ha numeric(12,2) not null default 0,
  estado text not null default 'pendiente',
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.tarea (
  id bigint generated by default as identity primary key,
  hito_id bigint not null references public.hito(id) on delete cascade,
  proyecto_id bigint not null references public.proyecto(id) on delete cascade,
  predio_id bigint,
  nombre text not null,
  actividad_id text,
  unidad text default 'ha',
  cantidad_meta numeric(12,2) not null default 0,
  cantidad_acumulada numeric(12,2) not null default 0,
  estado text not null default 'pendiente',
  responsable text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create index if not exists idx_hito_proyecto_orden on public.hito(proyecto_id, orden, id);
create index if not exists idx_tarea_hito on public.tarea(hito_id);
create index if not exists idx_tarea_proyecto on public.tarea(proyecto_id);
create index if not exists idx_usuario_pin_activo on public.usuario(pin) where activo = true;

-- Evita que las fechas de actualización dependan de la aplicación.
create or replace function public.set_actualizado_en()
returns trigger language plpgsql as $$
begin
  new.actualizado_en = now();
  return new;
end;
$$;

drop trigger if exists usuario_actualizado_en on public.usuario;
create trigger usuario_actualizado_en before update on public.usuario for each row execute function public.set_actualizado_en();
drop trigger if exists proyecto_actualizado_en on public.proyecto;
create trigger proyecto_actualizado_en before update on public.proyecto for each row execute function public.set_actualizado_en();
drop trigger if exists hito_actualizado_en on public.hito;
create trigger hito_actualizado_en before update on public.hito for each row execute function public.set_actualizado_en();
drop trigger if exists tarea_actualizado_en on public.tarea;
create trigger tarea_actualizado_en before update on public.tarea for each row execute function public.set_actualizado_en();

